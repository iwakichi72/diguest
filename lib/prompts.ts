export function buildSummaryPrompt(theme: string, log: string): string {
  return `以下は思考の掘り下げセッションの対話ログです。
テーマ：${theme}

${log}

上記の対話から、以下の2つを生成してください：

1. 対話の要約（200字以内）
   - ユーザーが何を掘り下げようとしていたかを客観的に記述する
   - アドバイスや評価を中心にしない

2. 掘り出されたもの（箇条書き）
   - 対話を通じてユーザー自身が言語化できたこと
   - まだ言葉になりかけていること
   - 仮説や問いの形で残ったこと

マークダウンのコードブロックは使わず、純粋なJSONのみを返してください：
{"summary":"...","surfaced":["...","..."]}`
}
